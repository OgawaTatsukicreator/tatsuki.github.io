"""Deliver Home's existing styles in its first HTML response.

The shared stylesheets remain the source of truth for all pages. Home uses their
base, header, hero, controls, footer and responsive rules, plus the complete LP and
motion styles. Keeping its lower sections styled also preserves anchor positions,
early scrolling, large viewports and the JavaScript-free layout.

Run after changing those styles or Home's generated fonts:
    python scripts/build_home_styles.py
Verify without dependencies or network:
    python scripts/build_home_styles.py --check
"""

import argparse
from pathlib import Path
import re


START = "<!-- Home styles: generated by scripts/build_home_styles.py -->"
END = "<!-- End generated Home styles -->"


def section(text, start, end=None):
    """Fail if source section markers move, rather than silently dropping rules."""
    first = text.index(start)
    last = text.index(end, first) if end else len(text)
    return text[first:last]


def home_styles(root):
    common = (root / "css/portfolio-v2.css").read_text(encoding="utf-8-sig")
    # Retain the existing cascade order, including every responsive override.
    shared = common[:common.index("/* Shared category page layout */")]
    shared += section(common, ".v2-footer {", "/* About */")
    shared += section(common, "@media (max-width: 1040px)")
    sources = [
        (root / "css/fonts-index.css").read_text(encoding="utf-8-sig"),
        shared,
        (root / "css/lp.css").read_text(encoding="utf-8-sig"),
        (root / "css/motion.css").read_text(encoding="utf-8-sig"),
    ]
    # URLs were relative to css/. These rules will be inside root/index.html.
    css = "\n".join(sources).replace('url("../', 'url("')
    if "</style" in css.lower():
        raise ValueError("CSS contains an unsafe inline style terminator")
    # Only comments, indentation and empty lines are removed; declaration values,
    # selector spacing, media conditions, strings and rule order stay intact.
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    return "\n".join(line.strip() for line in css.splitlines() if line.strip())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    page = root / "index.html"
    html = page.read_text(encoding="utf-8-sig")
    block = f'{START}\n  <style id="home-styles">\n{home_styles(root)}\n  </style>\n  {END}'
    if START not in html or END not in html:
        raise SystemExit("Home's generated style markers are missing")
    before, tail = html.split(START, 1)
    _, after = tail.split(END, 1)
    expected = before + block + after
    if args.check:
        if html != expected:
            raise SystemExit("Home styles are stale. Run python scripts/build_home_styles.py")
        print("Home styles match their source CSS and font declarations.")
    else:
        page.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Updated Home's initial styles ({len(block.encode('utf-8')):,} bytes).")


if __name__ == "__main__":
    main()
